    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT "PK_MISSION"
        PRIMARY KEY (mission_id),

    CONSTRAINT "FK_MISSION_TOURSPOT"
        FOREIGN KEY (spot_id)
        REFERENCES public."TourSpot" (spot_id)
        ON DELETE CASCADE,

    CONSTRAINT "FK_MISSION_USER"
        FOREIGN KEY (user_id)
        REFERENCES public."User" (user_id)
        ON DELETE CASCADE,

    CONSTRAINT "UK_MISSION_USER_SPOT"
        UNIQUE (user_id, spot_id),

    CONSTRAINT "CK_MISSION_PERCENT"
        CHECK (
            "percent" BETWEEN 0 AND 100
        )
