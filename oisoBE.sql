BEGIN;


-- =========================================================
-- 1. User
-- 회원 정보
-- =========================================================

CREATE TABLE IF NOT EXISTS public."User"
(
    user_id                int8 GENERATED BY DEFAULT AS IDENTITY,
    has_travel_plan        bool NOT NULL DEFAULT false,
    travel_time            int8 NULL,
    travel_companion       int8 NULL,
    preferred_travel_theme int8 NULL,
    transportation_mode    int8 NULL,
    "language"             int8 NULL,
    nickname               varchar(100) NULL,

    provider               varchar(30) NULL,
    provider_user_id       varchar(100) NULL,
    email                  varchar(320) NULL,
    profile_image_url      varchar(2048) NULL,

    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT "PK_USER"
        PRIMARY KEY (user_id),

    CONSTRAINT "CK_USER_PROVIDER"
        CHECK (
            (
                provider IS NULL
                AND provider_user_id IS NULL
            )
            OR
            (
                provider IS NOT NULL
                AND provider_user_id IS NOT NULL
            )
        ),

    CONSTRAINT "CK_USER_TRAVEL_TIME"
        CHECK (
            travel_time IS NULL
            OR travel_time >= 0
        )
);


CREATE UNIQUE INDEX IF NOT EXISTS "UK_USER_PROVIDER_SUBJECT"
    ON public."User" (provider, provider_user_id)
    WHERE provider IS NOT NULL
      AND provider_user_id IS NOT NULL;


CREATE UNIQUE INDEX IF NOT EXISTS "UK_USER_EMAIL"
    ON public."User" (lower(email))
    WHERE email IS NOT NULL;



-- =========================================================
-- 2. TourSpot
-- 문화재, 관광지 기본 정보
-- =========================================================

CREATE TABLE IF NOT EXISTS public."TourSpot"
(
    spot_id         int8 GENERATED BY DEFAULT AS IDENTITY,
    "name"          varchar(255) NOT NULL,
    img             varchar(2048) NULL,
    "content"       text NULL,
    address         text NULL,
    can_parking     bool NULL,
    can_pet         bool NULL,
    crowd_level     int4 NULL,
    overview        text NULL,
    homepage        text NULL,
    map_x           float8 NULL,
    map_y           float8 NULL,
    content_id      int8 NULL,
    content_type_id int8 NULL,
    tel             varchar(100) NULL,

    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT "PK_TOURSPOT"
        PRIMARY KEY (spot_id),

    CONSTRAINT "CK_TOURSPOT_NAME"
        CHECK (btrim("name") <> ''),

    CONSTRAINT "CK_TOURSPOT_CROWD_LEVEL"
        CHECK (
            crowd_level IS NULL
            OR crowd_level BETWEEN 1 AND 5
        )
);


CREATE UNIQUE INDEX IF NOT EXISTS "UK_TOURSPOT_CONTENT_ID"
    ON public."TourSpot" (content_id)
    WHERE content_id IS NOT NULL;


CREATE INDEX IF NOT EXISTS "IX_TOURSPOT_CONTENT_TYPE_ID"
    ON public."TourSpot" (content_type_id);



-- =========================================================
-- 3. AccommodationDetail
-- 숙박 시설의 객실 상세 정보
-- =========================================================

CREATE TABLE IF NOT EXISTS public."AccommodationDetail"
(
    temp_room_id                int8 GENERATED BY DEFAULT AS IDENTITY,
    spot_id                     int8 NOT NULL,

    room_code                   text NULL,
    room_title                  text NULL,
    room_size_pyeong            text NULL,
    room_size_square_meter      text NULL,
    room_count                  text NULL,
    base_count                  text NULL,
    max_count                   text NULL,

    offseason_weekday_min_fee   text NULL,
    offseason_weekend_min_fee   text NULL,
    peak_season_weekday_min_fee text NULL,
    peak_season_weekend_min_fee text NULL,

    room_intro                  text NULL,

    has_bath_facility           text NULL,
    has_bath                    text NULL,
    has_home_theater            text NULL,
    has_air_condition           text NULL,
    has_tv                      text NULL,
    has_pc                      text NULL,
    has_cable                   text NULL,
    has_internet                text NULL,
    has_refrigerator            text NULL,
    has_toiletries              text NULL,
    has_sofa                    text NULL,
    has_cook                    text NULL,
    has_table                   text NULL,
    has_hairdryer               text NULL,

    CONSTRAINT "PK_ACCOMMODATIONDETAIL"
        PRIMARY KEY (temp_room_id),

    CONSTRAINT "FK_ACCOMMODATIONDETAIL_TOURSPOT"
        FOREIGN KEY (spot_id)
        REFERENCES public."TourSpot" (spot_id)
        ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS "IX_ACCOMMODATIONDETAIL_SPOT_ID"
    ON public."AccommodationDetail" (spot_id);


CREATE UNIQUE INDEX IF NOT EXISTS
    "UK_ACCOMMODATIONDETAIL_SPOT_ROOM_CODE"
    ON public."AccommodationDetail" (spot_id, room_code)
    WHERE room_code IS NOT NULL;



-- =========================================================
-- 4. TourStory
-- 관광지의 역사 이야기, 설화, 스토리 카드
-- =========================================================

CREATE TABLE IF NOT EXISTS public."TourStory"
(
    story_id   int8 GENERATED BY DEFAULT AS IDENTITY,
    spot_id    int8 NOT NULL,
    title      varchar(255) NOT NULL,
    sub_title  varchar(255) NULL,
    summary    text NULL,
    story      text NULL,
    img        varchar(2048) NULL,
    tip        text NULL,
    "comment"  text NULL,

    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT "PK_TOURSTORY"
        PRIMARY KEY (story_id),

    CONSTRAINT "FK_TOURSTORY_TOURSPOT"
        FOREIGN KEY (spot_id)
        REFERENCES public."TourSpot" (spot_id)
        ON DELETE CASCADE,

    CONSTRAINT "CK_TOURSTORY_TITLE"
        CHECK (btrim(title) <> '')
);


CREATE INDEX IF NOT EXISTS "IX_TOURSTORY_SPOT_ID"
    ON public."TourStory" (spot_id);



-- =========================================================
-- 5. HashTag
-- 스토리에 사용할 해시태그
-- =========================================================

CREATE TABLE IF NOT EXISTS public."HashTag"
(
    hashtag_id int8 GENERATED BY DEFAULT AS IDENTITY,
    "name"     varchar(100) NOT NULL,

    CONSTRAINT "PK_HASHTAG"
        PRIMARY KEY (hashtag_id),

    CONSTRAINT "CK_HASHTAG_NAME"
        CHECK (btrim("name") <> '')
);


CREATE UNIQUE INDEX IF NOT EXISTS "UK_HASHTAG_NAME"
    ON public."HashTag" (lower("name"));



-- =========================================================
-- 6. StoryCard_HashTag
-- TourStory와 HashTag의 N:M 중간 테이블
-- =========================================================

CREATE TABLE IF NOT EXISTS public."StoryCard_HashTag"
(
    story_id   int8 NOT NULL,
    hashtag_id int8 NOT NULL,

    CONSTRAINT "PK_STORYCARD_HASHTAG"
        PRIMARY KEY (story_id, hashtag_id),

    CONSTRAINT "FK_STORYCARD_HASHTAG_TOURSTORY"
        FOREIGN KEY (story_id)
        REFERENCES public."TourStory" (story_id)
        ON DELETE CASCADE,

    CONSTRAINT "FK_STORYCARD_HASHTAG_HASHTAG"
        FOREIGN KEY (hashtag_id)
        REFERENCES public."HashTag" (hashtag_id)
        ON DELETE CASCADE
);


CREATE INDEX IF NOT EXISTS "IX_STORYCARD_HASHTAG_HASHTAG_ID"
    ON public."StoryCard_HashTag" (hashtag_id);



-- =========================================================
-- 7. TourSpotNearbyPlace
-- 관광지 주변 카페, 음식점, 숙박 시설 등의 기본 정보
-- =========================================================

CREATE TABLE IF NOT EXISTS public."TourSpotNearbyPlace"
(
    tour_spot_nearby_course_id int8 GENERATED BY DEFAULT AS IDENTITY,
    spot_id                    int8 NOT NULL,

    "name"                     varchar(255) NOT NULL,
    category                   varchar(30) NULL,
    mood                       varchar(30) NULL,
    address                    text NULL,
    hompage_url                varchar(2048) NULL,

    content_id                 int8 NULL,
    content_type_id            int8 NULL,

    map_x                      float8 NULL,
    map_y                      float8 NULL,

    created_at                 timestamptz NOT NULL DEFAULT now(),
    updated_at                 timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT "PK_TOURSPOTNEARBYPLACE"
        PRIMARY KEY (tour_spot_nearby_course_id),

    CONSTRAINT "FK_TOURSPOTNEARBYPLACE_TOURSPOT"
        FOREIGN KEY (spot_id)
        REFERENCES public."TourSpot" (spot_id)
        ON DELETE CASCADE,

    CONSTRAINT "CK_TOURSPOTNEARBYPLACE_NAME"
        CHECK (btrim("name") <> '')
);


CREATE INDEX IF NOT EXISTS "IX_TOURSPOTNEARBYPLACE_SPOT_ID"
    ON public."TourSpotNearbyPlace" (spot_id);


CREATE INDEX IF NOT EXISTS "IX_TOURSPOTNEARBYPLACE_CATEGORY"
    ON public."TourSpotNearbyPlace" (category);


CREATE UNIQUE INDEX IF NOT EXISTS
    "UK_TOURSPOTNEARBYPLACE_SPOT_CONTENT"
    ON public."TourSpotNearbyPlace" (spot_id, content_id)
    WHERE content_id IS NOT NULL;



-- =========================================================
-- 8. NearbyPlaceDetail
