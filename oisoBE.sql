CREATE INDEX IF NOT EXISTS "IX_MISSION_USER_ID"
    ON public."Mission" (user_id);


CREATE INDEX IF NOT EXISTS "IX_MISSION_SPOT_ID"
    ON public."Mission" (spot_id);



-- =========================================================
-- 13. tour_ingest_execution
-- 관광 데이터 수집 작업 실행 기록
-- =========================================================

CREATE TABLE IF NOT EXISTS public.tour_ingest_execution
(
    id              int8 GENERATED BY DEFAULT AS IDENTITY,
    status          varchar(20) NOT NULL,
    started_at      timestamptz NOT NULL DEFAULT now(),
    finished_at     timestamptz NULL,
    processed_count int4 NOT NULL DEFAULT 0,
    failure_message text NULL,

    CONSTRAINT tour_ingest_execution_pkey
        PRIMARY KEY (id),

    CONSTRAINT ck_tour_ingest_execution_status
        CHECK (
            status IN (
                'RUNNING',
                'SUCCESS',
                'FAILED'
            )
        ),

    CONSTRAINT ck_tour_ingest_execution_processed_count
        CHECK (
            processed_count >= 0
        ),

    CONSTRAINT ck_tour_ingest_execution_finished_at
        CHECK (
            finished_at IS NULL
            OR finished_at >= started_at
        )
);


CREATE INDEX IF NOT EXISTS ix_tour_ingest_execution_started_at
    ON public.tour_ingest_execution (started_at DESC);


