-- =========================================================
-- 9. TourCourse
-- 회원이 생성하거나 저장한 관광 코스
-- =========================================================

CREATE TABLE IF NOT EXISTS public."TourCourse"
(
    tour_course_id int8 GENERATED BY DEFAULT AS IDENTITY,
    user_id        int8 NOT NULL,
    title          varchar(255) NOT NULL,

    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT "PK_TOURCOURSE"
        PRIMARY KEY (tour_course_id),

    CONSTRAINT "FK_TOURCOURSE_USER"
        FOREIGN KEY (user_id)
        REFERENCES public."User" (user_id)
        ON DELETE CASCADE,

    CONSTRAINT "CK_TOURCOURSE_TITLE"
        CHECK (btrim(title) <> '')
);


CREATE INDEX IF NOT EXISTS "IX_TOURCOURSE_USER_ID"
    ON public."TourCourse" (user_id);



-- =========================================================
-- 10. TourCourseItem
-- 관광 코스에 포함되는 관광지 또는 주변 장소
--
-- spot_id:
--   관광지 아이템일 때 사용
--
-- tour_spot_nearby_course_id:
--   카페, 음식점, 숙박 시설 등의 주변 장소일 때 사용
--
-- 두 컬럼 중 정확히 하나만 값이 있어야 한다.
-- =========================================================

CREATE TABLE IF NOT EXISTS public."TourCourseItem"
(
    item_id                    int8 GENERATED BY DEFAULT AS IDENTITY,
    tour_course_id             int8 NOT NULL,

    spot_id                    int8 NULL,
    tour_spot_nearby_course_id int8 NULL,

    item_order                 int8 NOT NULL,

    CONSTRAINT "PK_TOURCOURSEITEM"
        PRIMARY KEY (item_id),

    CONSTRAINT "FK_TOURCOURSEITEM_TOURCOURSE"
        FOREIGN KEY (tour_course_id)
        REFERENCES public."TourCourse" (tour_course_id)
        ON DELETE CASCADE,

    CONSTRAINT "FK_TOURCOURSEITEM_TOURSPOT"
        FOREIGN KEY (spot_id)
        REFERENCES public."TourSpot" (spot_id)
        ON DELETE RESTRICT,

    CONSTRAINT "FK_TOURCOURSEITEM_NEARBYPLACE"
        FOREIGN KEY (tour_spot_nearby_course_id)
        REFERENCES public."TourSpotNearbyPlace"
            (tour_spot_nearby_course_id)
        ON DELETE RESTRICT,

    CONSTRAINT "UK_TOURCOURSEITEM_ORDER"
        UNIQUE (tour_course_id, item_order),

    CONSTRAINT "CK_TOURCOURSEITEM_TARGET"
        CHECK (
            (
                spot_id IS NOT NULL
                AND tour_spot_nearby_course_id IS NULL
            )
            OR
            (
                spot_id IS NULL
                AND tour_spot_nearby_course_id IS NOT NULL
            )
        ),

    CONSTRAINT "CK_TOURCOURSEITEM_ORDER"
        CHECK (item_order >= 1)
);


CREATE INDEX IF NOT EXISTS "IX_TOURCOURSEITEM_TOURCOURSE_ID"
    ON public."TourCourseItem" (tour_course_id);


CREATE INDEX IF NOT EXISTS "IX_TOURCOURSEITEM_SPOT_ID"
    ON public."TourCourseItem" (spot_id)
    WHERE spot_id IS NOT NULL;


CREATE INDEX IF NOT EXISTS "IX_TOURCOURSEITEM_NEARBYPLACE_ID"
    ON public."TourCourseItem" (tour_spot_nearby_course_id)
    WHERE tour_spot_nearby_course_id IS NOT NULL;


CREATE UNIQUE INDEX IF NOT EXISTS
    "UK_TOURCOURSEITEM_TOURSPOT"
    ON public."TourCourseItem"
    (
        tour_course_id,
        spot_id
    )
    WHERE spot_id IS NOT NULL;


CREATE UNIQUE INDEX IF NOT EXISTS
    "UK_TOURCOURSEITEM_NEARBYPLACE"
    ON public."TourCourseItem"
    (
        tour_course_id,
        tour_spot_nearby_course_id
    )
    WHERE tour_spot_nearby_course_id IS NOT NULL;



-- =========================================================
-- 11. Memo
-- 회원의 관광 코스 후기, 평점, 진행 기록
-- =========================================================

CREATE TABLE IF NOT EXISTS public."Memo"
(
    history_id     int8 GENERATED BY DEFAULT AS IDENTITY,
    user_id        int8 NOT NULL,
    tour_course_id int8 NOT NULL,

    review         text NULL,
    rating         int4 NULL,
    progress       float8 NULL,
    img            varchar(2048) NULL,

    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT "PK_MEMO"
        PRIMARY KEY (history_id),

    CONSTRAINT "FK_MEMO_USER"
        FOREIGN KEY (user_id)
        REFERENCES public."User" (user_id)
        ON DELETE CASCADE,

    CONSTRAINT "FK_MEMO_TOURCOURSE"
        FOREIGN KEY (tour_course_id)
        REFERENCES public."TourCourse" (tour_course_id)
        ON DELETE CASCADE,

    CONSTRAINT "UK_MEMO_USER_TOURCOURSE"
        UNIQUE (user_id, tour_course_id),

    CONSTRAINT "CK_MEMO_RATING"
        CHECK (
            rating IS NULL
            OR rating BETWEEN 1 AND 5
        ),

    CONSTRAINT "CK_MEMO_PROGRESS"
        CHECK (
            progress IS NULL
            OR progress BETWEEN 0 AND 100
        )
);


CREATE INDEX IF NOT EXISTS "IX_MEMO_USER_ID"
    ON public."Memo" (user_id);


CREATE INDEX IF NOT EXISTS "IX_MEMO_TOURCOURSE_ID"
    ON public."Memo" (tour_course_id);



-- =========================================================
-- 12. Mission
-- 회원의 관광지별 미션 수행 상태
-- =========================================================

CREATE TABLE IF NOT EXISTS public."Mission"
(
    mission_id int8 GENERATED BY DEFAULT AS IDENTITY,
